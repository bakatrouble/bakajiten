void TestGzip::unpacksMembers() {
    const std::optional<QByteArray> empty = Gzip::unpack(blob(kEmptyGz, sizeof(kEmptyGz)));
    QVERIFY(empty.has_value());
    QVERIFY(empty->isEmpty());
    const std::optional<QByteArray> text = Gzip::unpack(blob(kTextGz, sizeof(kTextGz)));
    QVERIFY(text.has_value());
    QCOMPARE(text->size(), 7200);
    QVERIFY(text->startsWith("The quick brown fox"));
    QVERIFY(text->endsWith("lazy dog. "));
    const std::optional<QByteArray> named = Gzip::unpack(blob(kFnameGz, sizeof(kFnameGz)));
    QVERIFY(named.has_value());
    QCOMPARE(*named, QByteArray("named content ").repeated(50));
}

void TestGzip::rejectsCorrupt() {
    QVERIFY(!Gzip::unpack(QByteArray()).has_value());
    QVERIFY(!Gzip::unpack(QByteArray("not gzip at all")).has_value());
    // Wrong method (0x08 is deflate; anything else is unknown).
    QByteArray badMethod = blob(kShortGz, sizeof(kShortGz));
    badMethod[2] = 0x09;
    QVERIFY(!Gzip::unpack(badMethod).has_value());
    // Truncated stream and trailer alike read as incomplete.
    QVERIFY(!Gzip::unpack(blob(kShortGz, sizeof(kShortGz) - 10)).has_value());
    QVERIFY(!Gzip::unpack(blob(kShortGz, sizeof(kShortGz) - 1)).has_value());
    // ISIZE mismatch (one past the true length) fails the check.
    QByteArray badSize = blob(kShortGz, sizeof(kShortGz));
    badSize[badSize.size() - 4] = static_cast<char>(badSize[badSize.size() - 4] + 1);
    QVERIFY(!Gzip::unpack(badSize).has_value());
}
